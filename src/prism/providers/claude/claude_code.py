"""Deterministic capture of a local Claude Code session transcript.

Claude Code stores each session as a JSON Lines file. This adapter turns one
session into Prism's provider-neutral capture without any network access,
public link, or model involvement:

* one turn = one real user prompt + all assistant *text* that followed it
  before the next prompt;
* tool calls, tool results, thinking blocks, system/meta records, and sidechain
  (sub-agent) activity are never captured, and their volume is reported as an
  informational warning so the owner knows what was left out;
* turns with no assistant text are dropped and reported.

The transcript format is a Claude Code implementation detail, not a public
API. Unknown record shapes are skipped conservatively rather than guessed, and
the owner reviews the exact normalized text before anything is shared.

This adapter separately implements ``ProvenanceCaptureAdapter``
(``provenance()``, below): it can report *which file a tool call touched and
at which turn*, entirely outside the capture pipeline above — that data
never becomes part of an ``AdapterCapture`` and is only ever used, owner-side,
by the Phase 9 taint-tracking layer. See ``projection/provenance.py``.
"""

from __future__ import annotations

import hashlib
import json
import re
import unicodedata
from collections import Counter
from pathlib import Path
from typing import Any

from ...exceptions import (
    ConversationNotFoundError,
    UnsupportedContentError,
    UnsupportedSourceFormatError,
)
from ...models.capture import (
    AdapterCapture,
    AdapterMessage,
    CaptureInventory,
    CaptureMethod,
    CaptureSelection,
    CaptureSource,
    CaptureWarning,
    ConversationSummary,
    MessageRole,
    Platform,
    WarningSeverity,
)
from ...projection.provenance import ToolReadEvent


MAX_FILE_BYTES = 256 * 1024 * 1024
MAX_SESSIONS = 500
MAX_TURNS = 100_000
_META_PREFIXES = (
    "<command-name>",
    "<command-message>",
    "<local-command-",
    "<system-reminder>",
    "<user-prompt-submit-hook>",
    "Caveat: The messages below were generated by the user while running local commands",
    "[Request interrupted by user",
)
_TITLE_LIMIT = 200

# Tool names worth recording as provenance events: ones that touch a local
# file or run an arbitrary command, which is the class of tool call that can
# introduce content into the agent's context the owner didn't mean to. Other
# tools (TodoWrite, WebFetch, ...) are not file-provenance-relevant and would
# only add noise to a list the owner has to review.
_PROVENANCE_TOOLS = frozenset({"Read", "Write", "Edit", "NotebookEdit", "Bash", "Glob", "Grep"})
_COMMAND_LABEL_LIMIT = 200


def _normalize(value: str) -> str:
    return unicodedata.normalize("NFC", value.replace("\r\n", "\n").replace("\r", "\n"))


def _single_line(value: str, limit: int) -> str:
    collapsed = " ".join(value.split())
    return collapsed if len(collapsed) <= limit else collapsed[: limit - 1] + "…"


class _ParsedSession:
    def __init__(self) -> None:
        self.title: str | None = None
        self.custom_title: str | None = None
        self.turns: list[tuple[str, str, str]] = []  # (source id, prompt, answer)
        self.tool_uses = 0
        self.skipped_no_answer = 0
        self.sidechain_records = 0
        self.fingerprint = ""
        # (turn_index, tool_name, resource_label) — owner-only provenance,
        # never mixed into `turns` and never reachable from AdapterCapture.
        self.tool_events: list[tuple[int, str, str]] = []


class ClaudeCodeSessionAdapter:
    """Reads one ``<session>.jsonl`` file, or lists the sessions in a directory."""

    name = "claude-code-session"
    version = "claude-code-session/0.1.0"

    def inventory(self, source: CaptureSource) -> CaptureInventory:
        files = self._session_files(source.path)
        summaries: list[ConversationSummary] = []
        for path in files:
            parsed = self._parse(path)
            if not parsed.turns:
                continue
            summaries.append(
                ConversationSummary(
                    conversation_ref=self._ref(path),
                    title=self._title(parsed, path),
                    supported_message_count=len(parsed.turns) * 2,
                    warnings=self._warnings(parsed),
                )
            )
        if not summaries:
            raise UnsupportedContentError(
                "No Claude Code session with a completed prompt and answer was found"
            )
        return CaptureInventory(
            source_fingerprint=self._fingerprint(files),
            adapter_version=self.version,
            conversations=tuple(summaries),
        )

    def capture(
        self,
        source: CaptureSource,
        selection: CaptureSelection,
    ) -> AdapterCapture:
        for path in self._session_files(source.path):
            if self._ref(path) != selection.conversation_ref:
                continue
            parsed = self._parse(path)
            if not parsed.turns:
                raise UnsupportedContentError(
                    "The selected session has no completed prompt and answer"
                )
            messages: list[AdapterMessage] = []
            for index, (source_id, prompt, answer) in enumerate(parsed.turns, start=1):
                messages.append(
                    AdapterMessage(
                        source_message_id=f"{source_id}:user"[:500],
                        turn_index=index,
                        ordinal=2 * index - 1,
                        role=MessageRole.USER,
                        content=prompt,
                    )
                )
                messages.append(
                    AdapterMessage(
                        source_message_id=f"{source_id}:assistant"[:500],
                        turn_index=index,
                        ordinal=2 * index,
                        role=MessageRole.ASSISTANT,
                        content=answer,
                    )
                )
            return AdapterCapture(
                platform=Platform.CLAUDE,
                method=CaptureMethod.LOCAL_SESSION,
                source_fingerprint=parsed.fingerprint,
                conversation_ref=selection.conversation_ref,
                title=self._title(parsed, path),
                messages=tuple(messages),
                warnings=self._warnings(parsed),
            )
        raise ConversationNotFoundError("The selected Claude Code session was not found")

    def provenance(
        self,
        source: CaptureSource,
        selection: CaptureSelection,
    ) -> tuple[ToolReadEvent, ...]:
        """Report which file/command-touching tool calls happened, and when.

        Implements ``ProvenanceCaptureAdapter``. Structurally independent of
        ``capture()``: this never feeds into ``AdapterCapture`` and is used
        only by the owner-only Phase 9 taint-tracking layer. Re-parses the
        same session file; the events line up with ``capture()``'s turn
        numbering because both are derived from the same closed-turn logic.
        """

        for path in self._session_files(source.path):
            if self._ref(path) != selection.conversation_ref:
                continue
            parsed = self._parse(path)
            return tuple(
                ToolReadEvent(turn_index=turn_index, tool_name=name, resource_label=label)
                for turn_index, name, label in parsed.tool_events
            )
        raise ConversationNotFoundError("The selected Claude Code session was not found")

    @staticmethod
    def _tool_event(block: dict[str, Any]) -> tuple[str, str] | None:
        """Extract ``(tool_name, resource_label)`` from one ``tool_use`` block.

        Returns ``None`` for tool names outside ``_PROVENANCE_TOOLS`` (not
        file/command-relevant) or when nothing identifiable can be extracted.
        Never raises on an unexpected shape — conservative, like the rest of
        this adapter.
        """

        name = block.get("name")
        if not isinstance(name, str) or name not in _PROVENANCE_TOOLS:
            return None
        raw_input = block.get("input")
        input_dict = raw_input if isinstance(raw_input, dict) else {}
        for key in ("file_path", "path", "notebook_path"):
            value = input_dict.get(key)
            if isinstance(value, str) and value.strip():
                return name, _single_line(value.strip(), _COMMAND_LABEL_LIMIT)
        command = input_dict.get("command") or input_dict.get("pattern")
        if isinstance(command, str) and command.strip():
            return name, _single_line(command.strip(), _COMMAND_LABEL_LIMIT)
        return name, "(no identifiable resource)"

    # ------------------------------------------------------------------

    @staticmethod
    def _ref(path: Path) -> str:
        digest = hashlib.sha256(path.stem.encode("utf-8")).hexdigest()[:24]
        return f"cc_{digest}"

    @staticmethod
    def _fingerprint(files: list[Path]) -> str:
        digest = hashlib.sha256(b"PrismClaudeCodeSource-v1\0")
        for path in files:
            stat = path.stat()
            digest.update(f"{path.name}:{stat.st_size}:{int(stat.st_mtime)}\0".encode())
        return "sha256:" + digest.hexdigest()

    def _session_files(self, path: Path) -> list[Path]:
        resolved = path.expanduser()
        if resolved.is_file():
            if resolved.suffix != ".jsonl":
                raise UnsupportedSourceFormatError(
                    "A Claude Code session must be a .jsonl transcript file"
                )
            return [resolved]
        if resolved.is_dir():
            files = sorted(
                (item for item in resolved.glob("*.jsonl") if item.is_file()),
                key=lambda item: item.stat().st_mtime,
                reverse=True,
            )[:MAX_SESSIONS]
            if not files:
                raise UnsupportedSourceFormatError(
                    "The directory contains no Claude Code .jsonl session files"
                )
            return files
        raise UnsupportedSourceFormatError("The source path does not exist")

    def _parse(self, path: Path) -> _ParsedSession:
        size = path.stat().st_size
        if size > MAX_FILE_BYTES:
            raise UnsupportedSourceFormatError("The session file exceeds the size limit")
        parsed = _ParsedSession()
        digest = hashlib.sha256(b"PrismClaudeCodeSession-v1\0")
        prompt: str | None = None
        prompt_id = ""
        answers: list[str] = []
        # Buffered with the turn, not assigned an index until the turn is
        # actually kept: a tool-only turn that gets dropped (no assistant
        # text) must not leave its tool events pointing at an index the
        # *next* turn will then reuse.
        pending_events: list[tuple[str, str]] = []

        def close_turn() -> None:
            nonlocal prompt, answers, pending_events
            if prompt is None:
                return
            joined = "\n\n".join(item for item in answers if item.strip()).strip()
            if joined and len(parsed.turns) < MAX_TURNS:
                parsed.turns.append((prompt_id, prompt, joined))
                turn_index = len(parsed.turns)
                parsed.tool_events.extend(
                    (turn_index, name, label) for name, label in pending_events
                )
            elif not joined:
                parsed.skipped_no_answer += 1
            prompt, answers, pending_events = None, [], []

        with path.open("rb") as handle:
            for raw in handle:
                digest.update(raw)
                try:
                    record = json.loads(raw)
                except json.JSONDecodeError:
                    continue
                if not isinstance(record, dict):
                    continue
                kind = record.get("type")
                if kind == "custom-title" and isinstance(record.get("customTitle"), str):
                    parsed.custom_title = record["customTitle"]
                    continue
                if kind not in {"user", "assistant"}:
                    continue
                if record.get("isSidechain") is True:
                    parsed.sidechain_records += 1
                    continue
                message = record.get("message")
                content = message.get("content") if isinstance(message, dict) else None
                if kind == "user":
                    text = self._user_prompt(record, content)
                    if text is None:
                        continue  # tool results, meta, or command noise
                    close_turn()
                    prompt = text
                    prompt_id = str(record.get("uuid") or f"turn{len(parsed.turns) + 1}")
                    if parsed.title is None:
                        parsed.title = text
                else:
                    if prompt is None:
                        continue
                    if isinstance(content, list):
                        for block in content:
                            if not isinstance(block, dict):
                                continue
                            if block.get("type") == "text" and isinstance(
                                block.get("text"), str
                            ):
                                answers.append(_normalize(block["text"]))
                            elif block.get("type") == "tool_use":
                                parsed.tool_uses += 1
                                event = self._tool_event(block)
                                if event is not None:
                                    pending_events.append(event)
                    elif isinstance(content, str):
                        answers.append(_normalize(content))
        close_turn()
        parsed.fingerprint = "sha256:" + digest.hexdigest()
        return parsed

    @staticmethod
    def _user_prompt(record: dict[str, Any], content: object) -> str | None:
        if record.get("isMeta") is True:
            return None
        text: str | None = None
        if isinstance(content, str):
            text = content
        elif isinstance(content, list):
            if any(
                isinstance(block, dict) and block.get("type") == "tool_result"
                for block in content
            ):
                return None
            parts = [
                block["text"]
                for block in content
                if isinstance(block, dict)
                and block.get("type") == "text"
                and isinstance(block.get("text"), str)
            ]
            text = "\n".join(parts) if parts else None
        if text is None:
            return None
        text = _normalize(text).strip()
        if not text or text.startswith(_META_PREFIXES):
            return None
        return text

    def _title(self, parsed: _ParsedSession, path: Path) -> str:
        base = parsed.custom_title or parsed.title or path.stem
        return _single_line(_normalize(base), _TITLE_LIMIT) or path.stem

    @staticmethod
    def _warnings(parsed: _ParsedSession) -> tuple[CaptureWarning, ...]:
        warnings = [
            CaptureWarning(
                code="tool_activity_omitted",
                message=(
                    f"{parsed.tool_uses} tool calls, all tool results, and thinking "
                    "blocks are never captured; only prompts and assistant text are."
                ),
                severity=WarningSeverity.INFO,
            )
        ]
        if parsed.skipped_no_answer:
            warnings.append(
                CaptureWarning(
                    code="turns_without_text_dropped",
                    message=(
                        f"{parsed.skipped_no_answer} prompts had no assistant text "
                        "(tool-only or interrupted) and were dropped."
                    ),
                    severity=WarningSeverity.INFO,
                )
            )
        if parsed.sidechain_records:
            warnings.append(
                CaptureWarning(
                    code="sidechain_omitted",
                    message=(
                        f"{parsed.sidechain_records} sub-agent records were omitted."
                    ),
                    severity=WarningSeverity.INFO,
                )
            )
        return tuple(warnings)


